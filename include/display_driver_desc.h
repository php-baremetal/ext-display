/*
 * display_driver_desc_t: a panel driver that is not a device of a bus extension (an RGB panel on the chip's LCD
 * peripheral). ext-display registers its class Baremetal\Display\Driver\<php_class>, final, implementing
 * Baremetal\Output\Display; methods holds the driver's own methods followed by DISPLAY_FE. Since ext-display 1.2.
 */
#pragma once
#include <stddef.h>
typedef struct _zend_function_entry zend_function_entry;
typedef struct _zend_class_entry zend_class_entry;

typedef struct display_driver_desc {
    const char *name;                           /* "rgb" */
    const char *php_class;                      /* "Rgb" */
    const zend_function_entry *methods;
    void (*class_init)(zend_class_entry *ce);   /* optional: constants, and create_object with its own handlers
                                                   (clone_obj NULL: a clone would have no surface) */
} display_driver_desc_t;

/* The display_drivers registry, generated by the build from the packages that register into it
 * (extra.baremetal.register.display_drivers). NULL-terminated; empty when no driver is installed. */
extern const display_driver_desc_t *const display_drivers[];
extern const size_t display_drivers_count;
